PT_EN_MM = 25.4 / 72
LARGEUR_UTILE_MM = config.PAGE_W_MM - 2 * config.MARGIN_MM


def largeur_mm(texte: str, police: dict[str, int], taille_pt: float) -> float:
    """Largeur approchée du texte (sans crénage) ; caractère inconnu = largeur d'un « n »."""
    defaut = police["n"]
    return sum(police.get(c, defaut) for c in texte) / 1000 * taille_pt * PT_EN_MM
